/**
 * Zero-dependency browser/CJS bundling of src/index.js.
 * Browser: <script src="dist/rank-lib.js"></script> exposes globalThis.RankLib.
 * CommonJS: require('rank-lib-js') resolves to dist/rank-lib.cjs.
 * Keep this explicit to fail on newly introduced unsupported exports/imports.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(resolve(root, 'src/index.js'), 'utf8');
if (/^\s*import\s/m.test(source)) throw new Error('Build requires self-contained src/index.js (no imports)');
const exported = [...source.matchAll(/^export function (\w+)\s*\(/gm)].map(m => m[1]);
const expected = ['compileMask', 'count', 'generate'];
if (exported.join(',') !== expected.join(',')) {
  throw new Error(`Unexpected exports: ${exported.join(', ')}`);
}
const code = source.replace(/^export function /gm, 'function ');
if (/^\s*export\s/m.test(code)) throw new Error('Unrecognized export syntax');
const banner = '/* rank-lib-js v0.1.0 | browser UMD bundle | generated by npm run build */\n';
const bundle = `${banner}(function (root, factory) {\n` +
  `  'use strict';\n` +
  `  const api = factory();\n` +
  `  if (typeof module === 'object' && module.exports) module.exports = api;\n` +
  `  if (root) root.RankLib = api;\n` +
  `})(typeof globalThis !== 'undefined' ? globalThis : undefined, function () {\n` +
  `  'use strict';\n${code}\n` +
  `  return { compileMask, count, generate };\n` +
  `});\n`;
mkdirSync(resolve(root, 'dist'), { recursive: true });
writeFileSync(resolve(root, 'dist/rank-lib.js'), bundle);
writeFileSync(resolve(root, 'dist/rank-lib.cjs'), bundle);
console.log('Built dist/rank-lib.js (browser) and dist/rank-lib.cjs (CommonJS)');
